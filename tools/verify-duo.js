#!/usr/bin/env node
'use strict';
/*
 * Сторож очерёдности хода. У двух героев клавиши общие, и всё устройство
 * уровней держится на одном правиле:
 *
 *     сначала полностью ходит 'M', потом 'N'.
 *
 * Правило видно невооружённым глазом: если 'M' освободил клетку, 'N' входит в
 * неё в тот же такт, а наоборот — уже нет. Поменять очередь местами значит
 * молча сломать все записанные решения главы, поэтому она проверяется отдельно
 * и на голых картах, где видно только её.
 */
var path = require('path');
var root = path.join(__dirname, '..');
var Engine = require(path.join(root, 'js', 'engine.js')).Engine;

var bad = 0;
function check(title, want, got) {
  if (want === got) return;
  bad++;
  console.log('ОЧЕРЕДЬ ' + title + ': ждали «' + want + '», вышло «' + got + '»');
}
function place(map, moves) {
  var e = new Engine({ map: map, needed: 0 });
  var A = { U: { dir: 0 }, R: { dir: 1 }, D: { dir: 2 }, L: { dir: 3 } };
  moves.split('').forEach(function (c) { e.step(A[c]); });
  return e.heroes.map(function (m) { return m.out ? 'вышел' : m.x + ',' + m.y; }).join(' ');
}

// 1. Пара идёт «след в след»: 'M' впереди, уходит влево и в тот же такт
//    освобождает клетку — 'N' сразу занимает её. Двигаются оба.
check('M впереди, оба идут', '1,1 2,1', place(['########', '#.MN...#', '########'], 'L'));

// 2. Зеркало того же положения: впереди 'N'. Теперь 'M' ходит первым и упирается
//    в напарника, хотя тот в этом же такте уйдёт. Двигается только один — и это
//    не мелочь реализации, а рычаг, которым игрок разводит героев.
check('N впереди, идёт один', '3,1 1,1', place(['########', '#.NM...#', '########'], 'L'));

// 3. Погоня в тупик: 'N' упирается в стену, 'M' догоняет и встаёт вплотную.
//    Дальше стоят оба — один об стену, другой о живого напарника.
check('погоня в тупик', '5,1 6,1', place(['########', '#M..N..#', '########'], 'RRRR'));
check('дальше не сдвинуть', '5,1 6,1', place(['########', '#M..N..#', '########'], 'RRRRRRR'));

// 4. Выход по одному: вышедший убирается с поля и перестаёт мешать. 'N' идёт
//    первым (он ближе), 'M' всё это время заперт его спиной.
check('вышел первый', '5,1 вышел', place(['########', '#MN...E#', '########'], 'RRRRR'));
check('вышли оба', 'вышел вышел', place(['########', '#MN...E#', '########'], 'RRRRRR'));

// 5. Пока вышли не все, победы нет.
var e = new Engine({ map: ['########', '#MN...E#', '########'], needed: 0 });
'RRRRR'.split('').forEach(function () { e.step({ dir: 1 }); });
if (e.status === 'won') { bad++; console.log('ОЧЕРЕДЬ: победа засчитана, пока напарник ещё в шахте'); }
if (!e.heroes[1].out) { bad++; console.log('ОЧЕРЕДЬ: напарник должен был выйти первым'); }
if (e.heroes[0].out) { bad++; console.log('ОЧЕРЕДЬ: первый герой выйти ещё не мог'); }

if (bad) { console.log('Очерёдность хода нарушена: ' + bad); process.exit(1); }
console.log('Очерёдность хода: 9 проверок, правило «сначала M, потом N» соблюдается.');
