"""Базовый интерфейс уведомлялок."""

from __future__ import annotations

from ..models import Event, Trip, TripState


class Notifier:
    """Куда-то сообщает о поездке.

    Два способа предупредить пользователя:

    * ``push`` — сказать прямо сейчас (баннер, сообщение в Telegram, строка в консоли).
      Работает, только пока запущен ``tracker watch``.
    * ``sync`` — заранее положить запись с будильником в Напоминания / Календарь,
      чтобы сигнал прозвучал даже при выключенном трекере. Вызывается на каждом
      опросе: если ETA сдвинулся, запись переносится.
    """

    name = "base"
    #: доступна ли уведомлялка на этой машине
    available = True
    #: причина недоступности (показывается пользователю)
    unavailable_reason = ""

    def push(self, event: Event) -> None:
        """Сообщить о событии немедленно."""

    def sync(self, trip: Trip, state: TripState) -> None:
        """Создать или подвинуть заранее запланированные напоминания."""

    def cancel(self, trip: Trip) -> None:
        """Убрать запланированные напоминания — поездка закончилась."""
